# 3. Create migration
os.environ["PGPASSWORD"] = "postgres"
try:
    subprocess.run(["alembic", "revision", "-m", "add initial market metrics to signals"], check=True)
    
    migration_files = glob.glob("alembic/versions/*_add_initial_market_metrics_to_signals.py")
    if migration_files:
        migration_file = migration_files[0]
        with open(migration_file, "r") as f:
            mig_content = f.read()
        
        mig_old_upgrade = "def upgrade() -> None:\n    # ### commands auto generated by Alembic - please adjust! ###\n    pass\n    # ### end Alembic commands ###"
        mig_new_upgrade = """def upgrade() -> None:
    op.add_column("signals", sa.Column("volume_1h", sa.Float(), nullable=True))
    op.add_column("signals", sa.Column("volume_24h", sa.Float(), nullable=True))
    op.add_column("signals", sa.Column("price_change_5m", sa.Float(), nullable=True))
    op.add_column("signals", sa.Column("price_change_1h", sa.Float(), nullable=True))
    op.add_column("signals", sa.Column("price_change_24h", sa.Float(), nullable=True))
    op.add_column("signals", sa.Column("market_cap", sa.Float(), nullable=True))
    op.add_column("signals", sa.Column("fdv", sa.Float(), nullable=True))"""
        mig_content = mig_content.replace(mig_old_upgrade, mig_new_upgrade)
        
        mig_old_upgrade2 = "def upgrade() -> None:\n    pass"
        mig_content = mig_content.replace(mig_old_upgrade2, mig_new_upgrade)

        mig_old_downgrade = "def downgrade() -> None:\n    # ### commands auto generated by Alembic - please adjust! ###\n    pass\n    # ### end Alembic commands ###"
        mig_new_downgrade = """def downgrade() -> None:
    op.drop_column("signals", "fdv")
    op.drop_column("signals", "market_cap")
    op.drop_column("signals", "price_change_24h")
    op.drop_column("signals", "price_change_1h")
    op.drop_column("signals", "price_change_5m")
    op.drop_column("signals", "volume_24h")
    op.drop_column("signals", "volume_1h")"""
        mig_content = mig_content.replace(mig_old_downgrade, mig_new_downgrade)

        mig_old_downgrade2 = "def downgrade() -> None:\n    pass"
        mig_content = mig_content.replace(mig_old_downgrade2, mig_new_downgrade)

        with open(migration_file, "w") as f:
            f.write(mig_content)
        
        subprocess.run(["alembic", "upgrade", "head"], check=True)
except Exception as e:
    print("Alembic failed, using psql fallback:", e)
    subprocess.run([
        "psql", "-h", "localhost", "-U", "postgres", "-d", "meco", "-c", 
        "ALTER TABLE signals ADD COLUMN volume_1h FLOAT, ADD COLUMN volume_24h FLOAT, ADD COLUMN price_change_5m FLOAT, ADD COLUMN price_change_1h FLOAT, ADD COLUMN price_change_24h FLOAT, ADD COLUMN market_cap FLOAT, ADD COLUMN fdv FLOAT;"
    ])

subprocess.run(["git", "add", "."], check=True)
subprocess.run(["git", "commit", "-m", "Add comprehensive initial market metrics to signals"], check=True)
